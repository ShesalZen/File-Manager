param(
    [string]$ApkDirectory = "app/build/outputs/apk/debug",
    [string]$ReportPath = ""
)

$ErrorActionPreference = "Stop"
Add-Type -AssemblyName System.IO.Compression.FileSystem

$commonLibraries = @(
    "libandroidx.graphics.path.so", "libdatastore_shared_counter.so",
    "liblink2symlink.so", "libloader.so", "libmlkit_google_ocr_pipeline.so",
    "libonnxruntime.so", "libonnxruntime4j_jni.so", "libproot.so", "libtermux.so"
)
$expected = @{
    "armeabi-v7a" = @($commonLibraries + @("lib7za.so", "libtectonic.so"))
    "arm64-v8a" = @($commonLibraries + @("lib7za.so", "libloader32.so", "libtectonic.so"))
    "x86_64" = @($commonLibraries + @("lib7za.so", "libloader32.so", "libtectonic.so"))
}
$machineNames = @{ 0x03 = "x86"; 0x28 = "ARM"; 0x3e = "x86_64"; 0xb7 = "AArch64" }
$abiMachines = @{ "armeabi-v7a" = 0x28; "arm64-v8a" = 0xb7; "x86" = 0x03; "x86_64" = 0x3e }
$loaderMachines = @{ "arm64-v8a" = 0x28; "x86_64" = 0x03 }

function Get-ElfMachine([System.IO.Compression.ZipArchiveEntry]$Entry) {
    $stream = $Entry.Open()
    try {
        $header = New-Object byte[] 20
        if ($stream.Read($header, 0, 20) -ne 20) { throw "Short ELF header: $($Entry.FullName)" }
        if ($header[0] -ne 0x7f -or $header[1] -ne 0x45 -or $header[2] -ne 0x4c -or $header[3] -ne 0x46) {
            throw "Not an ELF file: $($Entry.FullName)"
        }
        return [BitConverter]::ToUInt16($header, 18)
    } finally {
        $stream.Dispose()
    }
}

function Get-Category([string]$Name) {
    if ($Name -like "lib/*") { return "native" }
    if ($Name -like "classes*.dex") { return "dex" }
    if ($Name -like "assets/*") { return "assets" }
    if ($Name -like "res/*") { return "resources" }
    return "other"
}

$apks = Get-ChildItem -LiteralPath $ApkDirectory -Filter "*.apk" | Sort-Object Name
if ($apks.Count -eq 0) { throw "No APKs found in $ApkDirectory" }
$lines = [System.Collections.Generic.List[string]]::new()
$warnings = [System.Collections.Generic.List[string]]::new()
$inventory = @()
$universalCategories = @{}
$lines.Add("# APK analysis")
$lines.Add("")
$lines.Add("Generated by ``tools/analyze_apks.ps1`` from ``$ApkDirectory``.")
$lines.Add("")

foreach ($apk in $apks) {
    $zip = [System.IO.Compression.ZipFile]::OpenRead($apk.FullName)
    try {
        $entries = @($zip.Entries)
        $native = @($entries | Where-Object { $_.FullName -match "^lib/[^/]+/[^/]+\.so$" })
        $abis = @($native | ForEach-Object { $_.FullName.Split('/')[1] } | Sort-Object -Unique)
        $hash = (Get-FileHash -LiteralPath $apk.FullName -Algorithm SHA256).Hash
        $inventory += [PSCustomObject]@{
            Name = $apk.Name
            Bytes = $apk.Length
            ABIs = $abis -join ", "
            Hash = $hash
        }
        $lines.Add("## $($apk.Name)")
        $lines.Add("")
        $lines.Add("- APK bytes: $($apk.Length)")
        $lines.Add("- SHA-256: ``$hash``")
        $lines.Add("- Entries: $($entries.Count)")
        $lines.Add("- ABIs: $($abis -join ', ')")
        if ($apk.Name -match "universal") {
            $missingAbis = @($expected.Keys | Where-Object { $_ -notin $abis })
            if ($missingAbis.Count -gt 0) {
                $warnings.Add("$($apk.Name): missing supported ABIs $($missingAbis -join ', ')")
            }
        }
        $lines.Add("")
        $lines.Add("### Largest entries")
        $lines.Add("")
        $lines.Add("| Entry | Uncompressed bytes | Compressed bytes |")
        $lines.Add("| --- | ---: | ---: |")
        foreach ($entry in $entries | Sort-Object Length -Descending | Select-Object -First 15) {
            $lines.Add("| ``$($entry.FullName)`` | $($entry.Length) | $($entry.CompressedLength) |")
        }
        $lines.Add("")
        $lines.Add("### Compressed size categories")
        $lines.Add("")
        $lines.Add("| Category | Entries | Uncompressed bytes | Compressed bytes |")
        $lines.Add("| --- | ---: | ---: | ---: |")
        $categories = $entries | Group-Object { Get-Category $_.FullName } | Sort-Object { ($_.Group | Measure-Object CompressedLength -Sum).Sum } -Descending
        if ($apk.Name -match "universal") {
            $universalCategories = @{}
            foreach ($group in $categories) {
                $universalCategories[$group.Name] = ($group.Group | Measure-Object CompressedLength -Sum).Sum
            }
        }
        foreach ($group in $categories) {
            $uncompressed = ($group.Group | Measure-Object Length -Sum).Sum
            $compressed = ($group.Group | Measure-Object CompressedLength -Sum).Sum
            $lines.Add("| $($group.Name) | $($group.Count) | $uncompressed | $compressed |")
        }
        $lines.Add("")
        $lines.Add("### Native libraries")
        $lines.Add("")
        $lines.Add("| ABI | Library | Bytes | ELF architecture |")
        $lines.Add("| --- | --- | ---: | --- |")
        foreach ($entry in $native | Sort-Object FullName) {
            $parts = $entry.FullName.Split('/')
            $abi = $parts[1]
            $name = $parts[2]
            $machine = Get-ElfMachine $entry
            $expectedMachine = if ($name -eq "libloader32.so") { $loaderMachines[$abi] } else { $abiMachines[$abi] }
            if ($expectedMachine -ne $machine) {
                $warnings.Add("$($apk.Name): $($entry.FullName) has ELF machine 0x$($machine.ToString('X2')), expected 0x$($expectedMachine.ToString('X2'))")
            }
            $lines.Add("| $abi | ``$name`` | $($entry.Length) | $($machineNames[[int]$machine]) |")
        }
        $lines.Add("")
        foreach ($abi in $abis) {
            $actual = @($native | Where-Object { $_.FullName -like "lib/$abi/*" } | ForEach-Object { Split-Path $_.FullName -Leaf } | Sort-Object)
            if (-not $expected.ContainsKey($abi)) {
                $warnings.Add("$($apk.Name): unsupported ABI directory $abi")
                continue
            }
            $wanted = @($expected[$abi] | Sort-Object)
            $missing = @($wanted | Where-Object { $_ -notin $actual })
            $unexpected = @($actual | Where-Object { $_ -notin $wanted })
            if ($missing.Count -gt 0) { $warnings.Add("$($apk.Name): $abi missing $($missing -join ', ')") }
            if ($unexpected.Count -gt 0) { $warnings.Add("$($apk.Name): $abi unexpected $($unexpected -join ', ')") }
        }
    } finally {
        $zip.Dispose()
    }
}

$lines.Add("## Artifact summary")
$lines.Add("")
$lines.Add("| APK | Bytes | MiB | ABIs |")
$lines.Add("| --- | ---: | ---: | --- |")
foreach ($item in $inventory) {
    $lines.Add("| ``$($item.Name)`` | $($item.Bytes) | $([math]::Round($item.Bytes / 1MB, 2)) | $($item.ABIs) |")
}
$lines.Add("")
$lines.Add("## Size interpretation")
$lines.Add("")
$lines.Add("- The universal debug APK contains the shared application plus native libraries for all three supported ABIs; it is therefore larger than each ABI split.")
$lines.Add("- Its compressed payload by category is native $([math]::Round($universalCategories['native'] / 1MB, 2)) MiB, dex $([math]::Round($universalCategories['dex'] / 1MB, 2)) MiB, and assets $([math]::Round($universalCategories['assets'] / 1MB, 2)) MiB.")
$lines.Add("- Tectonic, ONNX Runtime, ML Kit OCR, and the Tectonic cache account for much of the native and asset payload.")
$lines.Add("- Prefer ABI-specific APKs for direct sideloading. A universal APK is useful only when one artifact must support ARMv7, ARM64, and x86_64 devices.")
$lines.Add("- A release build with R8/resource shrinking is the appropriate size baseline; the figures in this report are unminified debug artifacts and should not be treated as release sizes.")
$lines.Add("- Further reductions require product decisions: moving optional OCR/ONNX/Tectonic functionality to on-demand modules, shipping a smaller Tectonic cache, or removing one of the supported ABIs. ABI filters alone do not shrink the universal APK.")
$lines.Add("")
$lines.Add("## Audit warnings")
$lines.Add("")
if ($warnings.Count -eq 0) {
    $lines.Add("- None.")
} else {
    foreach ($warning in $warnings) { $lines.Add("- $warning") }
}
$report = $lines -join [Environment]::NewLine
if ($ReportPath) {
    $reportDirectory = Split-Path -Parent $ReportPath
    if ($reportDirectory) { New-Item -ItemType Directory -Path $reportDirectory -Force | Out-Null }
    Set-Content -LiteralPath $ReportPath -Value $report -Encoding utf8
} else {
    Write-Output $report
}
if ($warnings.Count -gt 0) {
    Write-Error ($warnings -join [Environment]::NewLine)
    exit 1
}
